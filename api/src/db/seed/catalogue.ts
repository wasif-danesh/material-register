/**
 * A template for one kind of part.
 *
 * `description` and `partNumber` may contain `{name}` placeholders, each filled with a
 * random value from `options[name]`; both use the same picked values, so a 2000mm belt
 * gets a part number that also says 2000. In `partNumber`, `#` becomes a random digit
 * and `?` a random capital letter.
 */
export type PartFamily = {
  type: MaterialType;
  unit: UnitOfMeasure;
  description: string;
  options: Record<string, readonly string[]>;
  /** Empty for raw materials, which have no manufacturer or part number. */
  makers: readonly string[];
  partNumber: string | null;
  /** Lowest and highest unit price in AUD. */
  price: readonly [number, number];
  /** Lowest and highest quantity on hand. */
  stock: readonly [number, number];
  /** Relative share of the catalogue. */
  weight: number;
};

